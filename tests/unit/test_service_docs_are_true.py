# T-0158 criterion 8 — the `down` paragraph says what `down` does to a container
#
# The paragraph that was true for T-0033 says `down` stops a container by signalling the
# `docker run` front end ("it proxies signals"). On 2026-10-26 that left `astra-stt` running and
# holding the GPU: moshi-server is PID 1 with no handler, so the forwarded SIGTERM is dropped.
# After T-0158 a container record is stopped through the daemon by its recorded id, docker's grace
# period applies, and a daemon that cannot be asked keeps the record. The A17 paragraph above stays.
# =================================================================================================


def test_the_down_section_describes_the_container_stop():
    """T-0158 criterion 8: by recorded id, through the daemon (`docker stop`), after the grace
    period, with the record kept when the daemon cannot be asked."""
    section = down_section(SERVICES_README.read_text())
    flat = re.sub(r"\s+", " ", section)
    low = flat.lower()
    assert "docker stop" in low, (
        f"criterion 8: the `down` section says a container is stopped with `docker stop`:\n{section}"
    )
    assert re.search(r"recorded (container )?id|container id[^.]*record", low), (
        "criterion 8: …by the container id recorded in the state file (never the name):\n" + section
    )
    assert "grace" in low, f"criterion 8: …after docker's grace period:\n{section}"
    assert any(
        re.search(r"(cannot|could not|can't|can not) be asked|(cannot|could not) ask", sentence)
        and re.search(r"\bkeep|\bkept", sentence)
        for sentence in sentences(low)
    ), (
        "criterion 8: …and a daemon that cannot be asked keeps the record (one sentence says "
        f"both):\n{section}"
    )


def test_the_down_section_no_longer_says_signalling_the_front_end_stops_the_container():
    """T-0158 criterion 8, negative: it does not claim that `down` cannot stop a container that
    ignores SIGTERM, nor that a signal to the `docker run` front end is what stops the container.

    Pending with its positive twin: it only means something once the paragraph has been rewritten
    (today's text makes exactly the claim this row refuses, so it is red now for the right reason).
    """
    section = down_section(SERVICES_README.read_text())
    assert "docker stop" in section.lower(), "criterion 8: the rewrite has happened (see above)"
    for sentence in sentences(section):
        low = sentence.lower()
        assert not ("proxies signals" in low and "stops the container" in low), (
            "criterion 8: a SIGTERM proxied by the front end does not stop a container whose PID 1 "
            f"has no handler (the 2026-10-26 bug); this sentence says it does:\n{sentence}"
        )
        if "sigterm" in low and ("ignore" in low or "no handler" in low):
            assert not re.search(
                r"cannot stop|can't stop|by hand|not stopped|stays running", low
            ), (
                "criterion 8: `down` does stop a container whose workload ignores SIGTERM (docker "
                f"stop escalates inside the container after the grace); this sentence says it "
                f"cannot:\n{sentence}"
            )
