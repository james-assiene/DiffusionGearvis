def test_the_m1_literal_is_the_925e55d6_section():
    """Provenance of ``M1_SHA256`` (T-0094 criterion 7, re-pinned by T-0177 ruling C-R4): it is the hash of the
    section in ``hud/README.md`` at 925e55d6, the commit that rewrote step 4 for C3. Skips (never passes) on a clone
    without that commit."""
    gr.require_commits(M1_PIN_COMMIT)
