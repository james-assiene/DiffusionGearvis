"""The cases of the tool-call eval set v1 (T-0080b criterion 1), as authored. ``build.py`` resolves each
computer-control target against the rendered DOM and writes ``cases.jsonl``.

Counts (criterion 1): 30 ``google_search``, 30 ``click_at``, 30 ``type_at``, 15 ``scroll``, 15 ``press_key``
and 20 no-tool cases. Split, stratified by tool and fixed here: dev 10/10/10/5/5 + 8 no-tool, test
20/20/20/10/10 + 12 no-tool. Every computer-control case of a split uses a screen of the same split
(``screens.Screen.split``), so no frame is shared between dev and test.

Ground truth follows ``local_astra.toolcall.score.exact`` (T-0080a criterion 3, D1):

- ``google_search``: ``keywords`` -- every keyword must appear in the query (NFC, case-folded, whitespace runs
  collapsed, substring). Keywords are the named entities a reasonable query cannot avoid;
- ``click_at``: the target element's bbox;
- ``type_at``: the bbox, ``text`` (the user gives it verbatim, in quotes) and ``press_enter`` (every
  instruction says explicitly whether to press Enter / submit);
- ``scroll``: ``direction``;
- ``press_key``: ``combo`` from the D1 enum of ``tools_v1.json``.

For ``scroll``/``press_key`` the ``target`` is the region acted on when the screen shows one (the scrolled
container, the focused element); it is ``None`` for browser- or OS-level keys (a new tab, Alt+Tab) and is not
part of the ground truth.
"""

